/**
 * Fetch verified community committees matching criteria.
 */
export async function getCommittees(
  filters: CommitteeFilters = {}
): Promise<ApiResponse<CommitteeDirectoryResponse>> {
  try {
    let items = [...CANONICAL_COMMITTEES_REGISTRY]

    if (filters.category && filters.category !== 'ALL') {
      items = items.filter((c) => c.category === filters.category)
    }

    if (filters.status === 'ACTIVE') {
      items = items.filter((c) => c.is_active)
    }

    if (filters.search && filters.search.trim() !== '') {
      const q = filters.search.toLowerCase().trim()
      items = items.filter(
        (c) =>
          c.name.toLowerCase().includes(q) ||
          c.description.toLowerCase().includes(q) ||
          c.leadership_summary.head_name.toLowerCase().includes(q) ||
          (c.leadership_summary.secretary_name &&
            c.leadership_summary.secretary_name.toLowerCase().includes(q)) ||
          (c.headquarters && c.headquarters.toLowerCase().includes(q))
      )
    }

    const availableCategories: CommitteeCategory[] = [
      'ALL',
      'GOVERNANCE',
      'CENSUS',
      'WELFARE',
      'YOUTH_SPORTS',
      'WOMEN_CULTURAL',
      'EDUCATION',
      'HEALTH',
    ]

    return {
      data: {
        items,
        totalCount: items.length,
        availableCategories,
      },
      error: null,
    }
  } catch (err: unknown) {
    const errorMsg =
      err instanceof Error ? err.message : 'Failed to fetch committees directory.'
    return {
      data: null,
      error: {
        message: errorMsg,
        code: 'COMMITTEES_FETCH_ERROR',
      },
    }
  }
}

/**
 * Fetch a single committee by ID or slug.
 */
export async function getCommitteeById(
  idOrSlug: string
): Promise<ApiResponse<Committee | null>> {
  try {
    const committee =
      CANONICAL_COMMITTEES_REGISTRY.find(
        (c) => c.id === idOrSlug || c.slug === idOrSlug
      ) || null

    return {
      data: committee,
      error: null,
    }
  } catch (err: unknown) {
    const errorMsg =
      err instanceof Error ? err.message : 'Failed to fetch committee details.'
    return {
      data: null,
      error: {
        message: errorMsg,
        code: 'COMMITTEE_DETAIL_ERROR',
      },
    }
  }
}
