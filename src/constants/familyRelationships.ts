/**
 * Flat lookup maps for O(1) retrieval across codes, canonical keys, English labels, and full display labels.
 */
const codeToItemMap = new Map<string, RelationshipItem>()
const keyToItemMap = new Map<string, RelationshipItem>()
const englishToItemMap = new Map<string, RelationshipItem>()
const displayToItemMap = new Map<string, RelationshipItem>()

for (const cat of FAMILY_RELATIONSHIP_CATEGORIES) {
  for (const item of cat.items) {
    if (item.relationshipCode) {
      codeToItemMap.set(item.relationshipCode.toUpperCase(), item)
    }
    keyToItemMap.set(item.canonicalKey.toLowerCase(), item)
    englishToItemMap.set(item.englishLabel.toLowerCase(), item)
    displayToItemMap.set(item.displayLabel.toLowerCase(), item)
  }
}

/**
 * Flat list of all official relationships in English.
 */
export const ALL_FAMILY_RELATIONSHIPS: string[] = FAMILY_RELATIONSHIP_CATEGORIES.flatMap((c) =>
  c.items.map((i) => i.englishLabel)
)

/**
 * Flat list of all display labels: "English (Hindi)".
 */
export const ALL_DISPLAY_RELATIONSHIPS: string[] = FAMILY_RELATIONSHIP_CATEGORIES.flatMap((c) =>
  c.items.map((i) => i.displayLabel)
)

/**
 * Resolves a relationship item by stable UPPERCASE code (e.g. 'FATHER', 'NEPHEWS_WIFE').
 */
export function getRelationshipByCode(code: string | null | undefined): RelationshipItem | undefined {
  if (!code) return undefined
  const upper = code.trim().toUpperCase()
  if (codeToItemMap.has(upper)) return codeToItemMap.get(upper)
  const snake = upper.replace(/\s+/g, '_')
  return codeToItemMap.get(snake)
}

/**
 * Resolves a relationship item by canonical key, English label, Hindi label, stable code, or composite string.
 */
export function getRelationshipDefinition(value: string | null | undefined): RelationshipItem | undefined {
  if (!value) return undefined
  const norm = value.trim()
  const lower = norm.toLowerCase()
  const upper = norm.toUpperCase()

  // 1. Direct code match
  if (codeToItemMap.has(upper)) return codeToItemMap.get(upper)
  // 2. Direct canonicalKey match
  if (keyToItemMap.has(lower)) return keyToItemMap.get(lower)
  // 3. Direct English label match
  if (englishToItemMap.has(lower)) return englishToItemMap.get(lower)
  // 4. Direct Display label match
  if (displayToItemMap.has(lower)) return displayToItemMap.get(lower)

  // 5. Try stripping Hindi bracket e.g. "Father (पिता)" -> "Father"
  const bracketMatch = value.match(/^([^(]+?)\s*\(([^)]+)\)$/)
  if (bracketMatch) {
    const eng = bracketMatch[1].trim().toLowerCase()
    if (englishToItemMap.has(eng)) return englishToItemMap.get(eng)
    if (keyToItemMap.has(eng.replace(/\s+/g, '_'))) return keyToItemMap.get(eng.replace(/\s+/g, '_'))
    const engCode = eng.replace(/[^a-zA-Z0-9]+/g, '_').toUpperCase()
    if (codeToItemMap.has(engCode)) return codeToItemMap.get(engCode)
  }

  // 6. Match by sanitized snake_case
  const snake = lower.replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '')
  if (keyToItemMap.has(snake)) return keyToItemMap.get(snake)
  if (codeToItemMap.has(snake.toUpperCase())) return codeToItemMap.get(snake.toUpperCase())

  // 7. Search across Hindi labels
  for (const cat of FAMILY_RELATIONSHIP_CATEGORIES) {
    for (const item of cat.items) {
      if (item.hindiLabel.toLowerCase().includes(lower) || lower.includes(item.hindiLabel.toLowerCase())) {
        return item
      }
    }
  }

  return undefined
}

/**
 * Formats any relationship value into the canonical "English (Hindi)" representation.
 * If the value is a custom "Other: XYZ", preserves it cleanly.
 */
export function formatRelationshipDisplay(value: string | null | undefined): string {
  if (!value) return ''
  const trimmed = value.trim()
  if (!trimmed) return ''

  if (trimmed.startsWith('Other: ') || trimmed.startsWith('Other (अन्य / विशिष्ट संबंध): ')) {
    return trimmed
  }

  // Simplify composite in-law and nephew labels for clean display matching reference designs
  if (/sister-in-law.*भाभी|bhabhi/i.test(trimmed)) {
    return 'Sister-in-law (भाभी)'
  }
  if (/nephew.*wife|भतीजे की पत्नी/i.test(trimmed)) {
    return "Nephew's Wife (भतीजे की पत्नी)"
  }
  if (/nephew.*भतीजा/i.test(trimmed)) {
    return 'Nephew (भतीजा)'
  }

  const def = getRelationshipDefinition(trimmed)
  if (def) {
    if (def.canonicalKey === 'sister_in_law' && /भाभी/.test(trimmed)) {
      return 'Sister-in-law (भाभी)'
    }
    if (def.canonicalKey === 'nephew' && /भतीजा/.test(trimmed)) {
      return 'Nephew (भतीजा)'
    }
    return def.displayLabel
  }

  return trimmed
}

/**
 * Resolves reciprocal relationship based on the relationship and target person's gender.
 */
export function getReciprocalRelationship(
  relationshipOrKey: string | null | undefined,
  targetGender?: 'MALE' | 'FEMALE' | 'OTHER' | null
): RelationshipItem | undefined {
  const def = getRelationshipDefinition(relationshipOrKey)
  if (!def) return undefined

  let reciprocalKey: string | undefined
  if (targetGender === 'MALE' && def.reciprocalKeyMale) {
    reciprocalKey = def.reciprocalKeyMale
  } else if (targetGender === 'FEMALE' && def.reciprocalKeyFemale) {
    reciprocalKey = def.reciprocalKeyFemale
  } else {
    reciprocalKey = def.reciprocalKeyNeutral || def.reciprocalKeyMale || def.reciprocalKeyFemale
  }

  if (!reciprocalKey) return undefined
  return getRelationshipDefinition(reciprocalKey)
}

/**
 * Maps any relationship string to a valid database public.family_role enum value:
 * 'HEAD' | 'SPOUSE' | 'CHILD' | 'PARENT' | 'SIBLING' | 'GRANDPARENT' | 'GRANDCHILD' | 'EXTENDED'
 */
export function mapRelationshipToFamilyRole(relationship: string | null | undefined): FamilyRole {
  if (!relationship) return 'EXTENDED'
  const norm = relationship.trim().toLowerCase()

  if (norm === 'head' || norm === 'head of family') {
    return 'HEAD'
  }

  const def = getRelationshipDefinition(relationship)
  if (def) {
    return def.familyRole
  }

  // Fallback heuristic for custom strings
  if (norm.includes('spouse') || norm.includes('wife') || norm.includes('husband') || norm.includes('partner')) {
    return 'SPOUSE'
  }
  if (norm.includes('father') || norm.includes('mother') || norm.includes('parent')) {
    return 'PARENT'
  }
  if (norm.includes('son') || norm.includes('daughter') || norm.includes('child')) {
    return 'CHILD'
  }
  if (norm.includes('brother') || norm.includes('sister') || norm.includes('sibling')) {
    return 'SIBLING'
  }
  if (norm.includes('grandfather') || norm.includes('grandmother') || norm.includes('grandparent') || norm.includes('ancestor')) {
    return 'GRANDPARENT'
  }
  if (norm.includes('grandson') || norm.includes('granddaughter') || norm.includes('grandchild') || norm.includes('descendant')) {
    return 'GRANDCHILD'
  }

  return 'EXTENDED'
}
