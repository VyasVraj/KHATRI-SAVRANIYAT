UPDATE public.cities c
SET country_id = co.id
FROM public.countries co
WHERE c.country_id IS NULL AND lower(trim(c.country)) = lower(trim(co.country_name));

UPDATE public.cities c
SET state_id = s.id
FROM public.states s
WHERE c.state_id IS NULL AND c.country_id = s.country_id AND lower(trim(c.state)) = lower(trim(s.state_name));

